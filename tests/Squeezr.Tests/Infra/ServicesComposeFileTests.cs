using Shouldly;
using Squeezr.Core.Infra;

namespace Squeezr.Tests.Infra;

public sealed class ServicesComposeFileTests
{
    [Fact]
    public void Generate_WithRocm_IncludesDevicesUnderOllamaOnly()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: true);

        content.ShouldContain("- /dev/kfd");
        content.ShouldContain("- /dev/dri");
        var qdrantSection = content.Split("  ollama:")[0];
        qdrantSection.ShouldNotContain("devices");
    }

    [Fact]
    public void Generate_WithoutRocm_OmitsDevicesSection()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        content.ShouldNotContain("devices");
    }

    [Fact]
    public void Generate_FirstLine_IsManagedByMarkerHeader()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        content.Split('\n')[0].ShouldBe(
            ServicesComposeFile.ManagedByMarker + " — do not edit ( regenerated by 'squeezr services up' )");
    }

    [Fact]
    public void Generate_QdrantService_HasImagePortsVolumeAndRestart()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        content.ShouldContain("qdrant/qdrant:latest");
        content.ShouldContain("- \"6333:6333\"");
        content.ShouldContain("- \"6334:6334\"");
        content.ShouldContain($"- {ServicesComposeFile.QdrantVolumeName}:/qdrant/storage");
        content.ShouldContain("restart: unless-stopped");
    }

    [Fact]
    public void Generate_OllamaService_HasImagePortVolumeAndRestart()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        content.ShouldContain("ollama/ollama:latest");
        content.ShouldContain("- \"11434:11434\"");
        content.ShouldContain($"- {ServicesComposeFile.OllamaVolumeName}:/root/.ollama");
        content.ShouldContain("restart: unless-stopped");
    }

    [Fact]
    public void Generate_DeclaresBothNamedVolumes()
    {
        var content = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        content.ShouldContain("volumes:");
        content.ShouldContain($"  {ServicesComposeFile.QdrantVolumeName}:");
        content.ShouldContain($"  {ServicesComposeFile.OllamaVolumeName}:");
    }

    [Fact]
    public void Generated_Content_UsesMarkerAndVolumeConstants()
    {
        var withRocm = ServicesComposeFile.Generate(rocmDevicesAvailable: true);
        var withoutRocm = ServicesComposeFile.Generate(rocmDevicesAvailable: false);

        withRocm.ShouldContain(ServicesComposeFile.ManagedByMarker);
        withoutRocm.ShouldContain(ServicesComposeFile.ManagedByMarker);
        withRocm.ShouldContain(ServicesComposeFile.QdrantVolumeName);
        withRocm.ShouldContain(ServicesComposeFile.OllamaVolumeName);
    }

    [Fact]
    public void Write_WithoutRocm_ThenWithRocm_RegeneratesSameFile()
    {
        var withoutRocmPath = ServicesComposeFile.Write(rocmDevicesAvailable: false);
        File.ReadAllText(withoutRocmPath).ShouldNotContain("devices");

        var withRocmPath = ServicesComposeFile.Write(rocmDevicesAvailable: true);

        withRocmPath.ShouldBe(withoutRocmPath);
        withRocmPath.ShouldBe(Path.Combine(ServicesComposeFile.InfraDir, "docker-compose.yml"));
        var regenerated = File.ReadAllText(withRocmPath);
        regenerated.ShouldContain("devices");
        regenerated.ShouldContain("- /dev/kfd");
    }

    [Fact]
    public void IsSqueezrGenerated_GeneratedFile_ReturnsTrue()
    {
        var path = Path.Combine(TestDirs.NewTempDir(), "docker-compose.yml");
        File.WriteAllText(path, ServicesComposeFile.Generate(rocmDevicesAvailable: true));

        ServicesComposeFile.IsSqueezrGenerated(path).ShouldBeTrue();
    }

    [Fact]
    public void IsSqueezrGenerated_LegacyQdrantOnlyCompose_ReturnsTrue()
    {
        var path = Path.Combine(TestDirs.NewTempDir(), "docker-compose.yml");
        File.WriteAllText(path, "services:\n  qdrant:\n    volumes:\n      - squeezr-qdrant:/qdrant/storage\n");

        ServicesComposeFile.IsSqueezrGenerated(path).ShouldBeTrue();
    }

    [Fact]
    public void IsSqueezrGenerated_ForeignCompose_ReturnsFalse()
    {
        var path = Path.Combine(TestDirs.NewTempDir(), "docker-compose.yml");
        File.WriteAllText(path, "services:\n  nginx:\n    image: nginx:latest\n");

        ServicesComposeFile.IsSqueezrGenerated(path).ShouldBeFalse();
    }

    [Fact]
    public void IsSqueezrGenerated_MissingFile_ReturnsFalse()
    {
        var path = Path.Combine(TestDirs.NewTempDir(), "absent.yml");

        ServicesComposeFile.IsSqueezrGenerated(path).ShouldBeFalse();
    }

    [Fact]
    public void TryReadRocmEnabled_GeneratedWithRocm_ReturnsTrue()
    {
        ServicesComposeFile.Write(rocmDevicesAvailable: true);

        ServicesComposeFile.TryReadRocmEnabled().ShouldBe(true);
    }

    [Fact]
    public void TryReadRocmEnabled_GeneratedWithoutRocm_ReturnsFalse()
    {
        ServicesComposeFile.Write(rocmDevicesAvailable: false);

        ServicesComposeFile.TryReadRocmEnabled().ShouldBe(false);
    }

    [Fact]
    public void TryReadRocmEnabled_MissingComposeFile_ReturnsNull()
    {
        var composePath = ServicesComposeFile.ComposeFilePath;
        if (File.Exists(composePath))
        {
            File.Delete(composePath);
        }

        ServicesComposeFile.TryReadRocmEnabled().ShouldBeNull();
    }
}
