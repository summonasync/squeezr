using System.Text;
using Squeezr.Core.Storage;

namespace Squeezr.Core.Infra;

public static class ServicesComposeFile
{
    public const string ManagedByMarker = "# managed by squeezr";
    public const string ProjectName = "squeezr";
    public const string QdrantVolumeName = "squeezr-qdrant";
    public const string OllamaVolumeName = "squeezr-ollama";
    public const string QdrantEndpoint = "http://localhost:6333";
    public const string OllamaEndpoint = "http://localhost:11434";

    private const string Header = ManagedByMarker + " — do not edit ( regenerated by 'squeezr services up' )";
    private const string RestartPolicy = "unless-stopped";

    public static string InfraDir => Path.Combine(SqueezrHome.Resolve(), SqueezrPaths.InfraDirName);

    public static string ComposeFilePath => Path.Combine(InfraDir, SqueezrPaths.ComposeFileName);

    public static string Generate(bool rocmDevicesAvailable)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("services:");
        builder.AppendLine("  qdrant:");
        builder.AppendLine("    image: qdrant/qdrant:latest");
        builder.AppendLine("    ports:");
        builder.AppendLine("      - \"6333:6333\"");
        builder.AppendLine("      - \"6334:6334\"");
        builder.AppendLine("    volumes:");
        builder.AppendLine($"      - {QdrantVolumeName}:/qdrant/storage");
        builder.AppendLine($"    restart: {RestartPolicy}");
        builder.AppendLine("  ollama:");
        builder.AppendLine("    image: ollama/ollama:latest");
        builder.AppendLine("    ports:");
        builder.AppendLine("      - \"11434:11434\"");
        builder.AppendLine("    volumes:");
        builder.AppendLine($"      - {OllamaVolumeName}:/root/.ollama");
        builder.AppendLine($"    restart: {RestartPolicy}");
        if (rocmDevicesAvailable)
        {
            builder.AppendLine("    devices:");
            builder.AppendLine($"      - {RocmDeviceProbe.KfdDevicePath}");
            builder.AppendLine($"      - {RocmDeviceProbe.DriDevicePath}");
        }

        builder.AppendLine("volumes:");
        builder.AppendLine($"  {QdrantVolumeName}:");
        builder.AppendLine($"  {OllamaVolumeName}:");
        return builder.ToString();
    }

    public static string Write(bool rocmDevicesAvailable)
    {
        Directory.CreateDirectory(InfraDir);
        File.WriteAllText(ComposeFilePath, Generate(rocmDevicesAvailable));
        return ComposeFilePath;
    }

    public static bool? TryReadRocmEnabled()
    {
        if (!File.Exists(ComposeFilePath))
        {
            return null;
        }

        return File.ReadAllText(ComposeFilePath).Contains(RocmDeviceProbe.KfdDevicePath, StringComparison.Ordinal);
    }

    public static bool IsSqueezrGenerated(string path)
    {
        if (!File.Exists(path))
        {
            return false;
        }

        var content = File.ReadAllText(path);
        return content.Contains(ManagedByMarker, StringComparison.Ordinal) ||
               content.Contains(QdrantVolumeName, StringComparison.Ordinal);
    }
}
