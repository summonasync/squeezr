using System.Text;

namespace Squeezr.Semantic.Infra;

// the owned instance is a separate compose project so it never fights the legacy
// qdrant+ollama pair for ports, volumes, or lifecycle
public static class OwnedComposeFile
{
    public const string ManagedByMarker = "# managed by squeezr (owned instance)";
    public const string ProjectName = "squeezr-owned";
    public const string VolumeName = "squeezr-owned-qdrant";
    public const string RestEndpoint = "http://localhost:6335";
    public const string GrpcEndpoint = "http://localhost:6336";

    private const string Header = ManagedByMarker + " — do not edit (regenerated by 'squeezr services up')";

    public static string FilePath => Path.Combine(ServicesComposeFile.InfraDir, "docker-compose.owned.yml");

    public static string Generate(int restPort = 6335, int grpcPort = 6336)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Header);
        builder.AppendLine("services:");
        builder.AppendLine("  qdrant:");
        builder.AppendLine("    image: qdrant/qdrant:latest");
        builder.AppendLine("    ports:");
        builder.AppendLine($"      - \"{restPort}:6333\"");
        builder.AppendLine($"      - \"{grpcPort}:6334\"");
        builder.AppendLine("    volumes:");
        builder.AppendLine($"      - {VolumeName}:/qdrant/storage");
        builder.AppendLine("    restart: unless-stopped");
        builder.AppendLine("volumes:");
        builder.AppendLine($"  {VolumeName}:");
        return builder.ToString();
    }

    public static string Write(int restPort = 6335, int grpcPort = 6336)
    {
        Directory.CreateDirectory(ServicesComposeFile.InfraDir);
        File.WriteAllText(FilePath, Generate(restPort, grpcPort));
        return FilePath;
    }
}
